import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");

test("operator scripts use PluginName placeholder consistently", () => {
  const required = [
    "Setup-PluginName.ps1","Start-PluginName.ps1","Status-PluginName.ps1",
    "Stop-PluginName.ps1","Clear-PluginNameSettings.ps1"
  ];
  for (const name of required) {
    const file = path.join(root, name);
    assert.equal(fs.existsSync(file), true, name + " missing");
    assert.match(fs.readFileSync(file, "utf8"), /PluginName/);
  }
});

test("connection profile is generated by scripts rather than committed", () => {
  assert.equal(fs.existsSync(path.join(root, "mcp-conf.yaml")), false);
  const helper = fs.readFileSync(path.join(root, "scripts", "PluginNameSettings.ps1"), "utf8");
  assert.match(helper, /Write-PluginNameProfile/);
  assert.match(helper, /health_port/);
  assert.match(helper, /tunnel_id/);
  assert.match(helper, /organization_id/);
});
