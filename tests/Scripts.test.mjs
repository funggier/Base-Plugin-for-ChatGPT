import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");

test("operator scripts use the generic Plugin identity consistently", () => {
  const required = [
    "Setup-Plugin.ps1","Start-Plugin.ps1","Status-Plugin.ps1",
    "Stop-Plugin.ps1","Refresh-Plugin.ps1","Clear-PluginSettings.ps1"
  ];
  for (const name of required) {
    const file = path.join(root, name);
    assert.equal(fs.existsSync(file), true, name + " missing");
    assert.match(fs.readFileSync(file, "utf8"), /Plugin/);
  }
});

test("connection profile is generated by scripts rather than committed", () => {
  assert.equal(fs.existsSync(path.join(root, "mcp-conf.yaml")), false);
  const helper = fs.readFileSync(path.join(root, "scripts", "PluginSettings.ps1"), "utf8");
  assert.match(helper, /Write-PluginProfile/);
  assert.match(helper, /health_port/);
  assert.match(helper, /tunnel_id/);
  assert.match(helper, /organization_id/);
});

test("persistent plugin runtime is separated from generated tunnel runtime", () => {
  const helper = fs.readFileSync(path.join(root, "scripts", "PluginSettings.ps1"), "utf8");
  const refresh = fs.readFileSync(path.join(root, "Refresh-Plugin.ps1"), "utf8");
  assert.match(helper, /PersistentRuntime/);
  assert.match(helper, /Plugin-runtime/);
  assert.match(helper, /Clear-PluginGeneratedState/);
  assert.match(refresh, /runtime\//);
  assert.match(refresh, /logs\//);
  assert.match(refresh, /Plugin-runtime\/ \(plugin-owned drivers\/binaries\/cache\)/);
  assert.equal(fs.existsSync(path.join(root, "Plugin-runtime", ".gitkeep")), true);
});
